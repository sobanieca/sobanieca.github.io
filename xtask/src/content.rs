const CONTENT_DIR: &str = "src/content";

const HERO_DIR: &str = "public/assets/images/articles";

const INLINE_DIR: &str = "public/articles/images";

const HERO_EXTENSIONS: &[&str] = &["jpg", "jpeg", "png", "webp", "gif"];

const GENERATED: &str = "// Generated by cargo content (xtask/src/content.rs) - do not edit.\n";

const MONTHS: &[&str] = &[
    "January",
    "February",
    "March",
    "April",
    "May",
    "June",
    "July",
    "August",
    "September",
    "October",
    "November",
    "December",
];

pub struct Category {
    pub slug: String,
    pub name: String,
    pub description: String,
    order: i64,
    icon: String,
}

pub struct Article {
    pub slug: String,
    pub title: String,
    pub excerpt: String,
    key: String,
    date: String,
    order: u32,
    category: String,
    html: String,
    code: Vec<Value>,
    /// The hero image: its source file and the path it is served at
    image: Option<(String, String)>,
}

pub struct Site {
    pub categories: Vec<Category>,
    pub articles: Vec<Article>,
    pub about_title: String,
}

/// The key of a node in the imp application map. imp serves a camelCase key as a kebab-case path
/// segment, so `working-with-remote-machine` is the key `workingWithRemoteMachine`.
fn map_key(slug: &str) -> Result<String> {
    let valid = slug.starts_with(|c: char| c.is_ascii_lowercase())
        && !slug.ends_with('-')
        && !slug.contains("--")
        && slug
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    if !valid {
        bail!("\"{slug}\" cannot be a route - use lowercase words joined by single dashes");
    }
    let mut key = String::new();
    let mut upper = false;
    for char in slug.chars() {
        if char == '-' {
            upper = true;
        } else if upper {
            // `a-1b` would come back as the path `a1b`
            if !char.is_ascii_lowercase() {
                bail!("\"{slug}\" cannot be a route - start every word after a dash with a letter");
            }
            key.push(char.to_ascii_uppercase());
            upper = false;
        } else {
            key.push(char);
        }
    }
    Ok(key)
}

fn date_parts(date: &str) -> Option<(&str, usize, u32)> {
    let mut parts = date.split('-');
    let year = parts.next()?;
    let month: usize = parts.next()?.parse().ok()?;
    let day: u32 = parts.next()?.parse().ok()?;
    (year.len() == 4 && (1..=12).contains(&month) && (1..=31).contains(&day))
        .then_some((year, month, day))
}

/// `2025-01-02` is `January 2, 2025`
fn long_date(date: &str) -> String {
    match date_parts(date) {
        Some((year, month, day)) => format!("{} {day}, {year}", MONTHS[month - 1]),
        None => date.to_string(),
    }
}

/// `2025-01-02` is `02.01.2025`
fn short_date(date: &str) -> String {
    match date_parts(date) {
        Some((year, month, day)) => format!("{day:02}.{month:02}.{year}"),
        None => date.to_string(),
    }
}

fn sorted_entries(path: &str) -> Result<Vec<fs::DirEntry>> {
    let mut entries = fs::read_dir(path)
        .with_context(|| format!("cannot read {path}"))?
        .collect::<std::io::Result<Vec<_>>>()?;
    entries.sort_by_key(|entry| entry.file_name());
    Ok(entries)
}

fn read_categories() -> Result<Vec<Category>> {
    let mut categories = Vec::new();
    for entry in sorted_entries("articles")? {
        if !entry.file_type()?.is_dir() {
            continue;
        }
        let slug = entry.file_name().to_string_lossy().into_owned();
        let path = entry.path();
        let Ok(yaml) = fs::read_to_string(path.join("category.yaml")) else {
            eprintln!("Warning: No category.yaml found in articles/{slug}");
            continue;
        };
        let fields = Fields::parse(&yaml);
        let icon = fs::read_to_string(path.join("category-icon.svg")).unwrap_or_default();
        categories.push(Category {
            name: fields.get("name").unwrap_or(&slug).to_string(),
            description: fields.get("description").unwrap_or("").to_string(),
            order: fields
                .get("order")
                .and_then(|order| order.parse().ok())
                .unwrap_or(999),
            icon: icon.trim().to_string(),
            slug,
        });
    }
    categories.sort_by_key(|category| category.order);
    Ok(categories)
}

fn read_articles(categories: &[Category]) -> Result<Vec<Article>> {
    let slugs: Vec<String> = categories.iter().map(|c| c.slug.clone()).collect();
    let mut articles: Vec<Article> = Vec::new();
    for category in categories {
        let dir = format!("articles/{}", category.slug);
        for entry in sorted_entries(&dir)? {
            let file = entry.file_name().to_string_lossy().into_owned();
            let Some(base) = file.strip_suffix(".md") else {
                continue;
            };
            let text = fs::read_to_string(entry.path())?;
            let (fields, body) = frontmatter::split(&text);
            let digits: String = base.chars().take_while(char::is_ascii_digit).collect();
            let slug = match base.split_once('-') {
                Some((order, rest)) if order == digits && !digits.is_empty() => rest,
                _ => base,
            }
            .to_string();
            let rendered = markdown::render(body, &slugs, CodeBlocks::Placeholders);
            let image = HERO_EXTENSIONS.iter().find_map(|extension| {
                let source = format!("{dir}/{base}.{extension}");
                Path::new(&source).is_file().then(|| {
                    (
                        source,
                        format!("/assets/images/articles/{slug}.{extension}"),
                    )
                })
            });
            if let Some(existing) = articles.iter().find(|article| article.slug == slug) {
                bail!(
                    "Duplicate article slug \"{slug}\"\n  - {}/{slug} ({})\n  - {}/{slug} ({})",
                    existing.category,
                    existing.date,
                    category.slug,
                    fields.get("date").unwrap_or("")
                );
            }
            articles.push(Article {
                key: map_key(&slug)?,
                title: fields.get("title").unwrap_or("Untitled").to_string(),
                excerpt: fields.get("excerpt").unwrap_or("").to_string(),
                date: fields.get("date").unwrap_or("").to_string(),
                order: digits.parse().unwrap_or(0),
                category: category.slug.clone(),
                html: rendered.html,
                code: rendered.code,
                image,
                slug,
            });
        }
    }
    // Most recently updated first, then by order
    articles.sort_by(|a, b| b.date.cmp(&a.date).then(b.order.cmp(&a.order)));
    Ok(articles)
}

fn url_of(article: &Article) -> String {
    format!("/articles/{}", article.slug)
}

fn link_of(article: &Article) -> Value {
    json!({ "title": article.title, "url": url_of(article) })
}

fn site_data(categories: &[Category], articles: &[Article], about: &Value) -> Result<String> {
    // The articles of a category in reading order, for the previous and next links
    let in_category = |slug: &str| -> Vec<&Article> {
        let mut list: Vec<&Article> = articles.iter().filter(|a| a.category == slug).collect();
        list.sort_by_key(|article| article.order);
        list
    };
    let category_data: Vec<Value> = categories
        .iter()
        .map(|category| {
            json!({
                "slug": category.slug,
                "name": category.name,
                "description": category.description,
                "icon": category.icon,
                "url": format!("/category/{}", category.slug),
            })
        })
        .collect();
    let article_data: Vec<Value> = articles
        .iter()
        .map(|article| {
            let siblings = in_category(&article.category);
            let index = siblings
                .iter()
                .position(|a| a.slug == article.slug)
                .unwrap_or(0);
            // "prev" (←) = lower order, "next" (→) = higher order
            let prev = index.checked_sub(1).and_then(|i| siblings.get(i));
            let next = siblings.get(index + 1);
            let next_category = match next {
                Some(_) => None,
                None => categories
                    .iter()
                    .skip_while(|c| c.slug != article.category)
                    .skip(1)
                    .find(|c| !in_category(&c.slug).is_empty()),
            };
            json!({
                "slug": article.slug,
                "title": article.title,
                "excerpt": article.excerpt,
                "date": article.date,
                "dateLong": long_date(&article.date),
                "dateShort": short_date(&article.date),
                "order": article.order,
                "category": article.category,
                "url": url_of(article),
                "image": article.image.as_ref().map(|(_, served)| served),
                "prev": prev.map(|a| link_of(a)),
                "next": next.map(|a| link_of(a)),
                "nextCategory": next_category.map(|c| json!({
                    "name": c.name,
                    "url": format!("/category/{}", c.slug),
                })),
            })
        })
        .collect();
    Ok(format!(
        "{GENERATED}
// Every category, in the order of the sidebar
export const categories = {}

// Every article without its body, most recently updated first
export const articles = {}

export const about = {}
",
        serde_json::to_string_pretty(&category_data)?,
        serde_json::to_string_pretty(&article_data)?,
        serde_json::to_string_pretty(about)?,
    ))
}

fn read_about(categories: &[Category]) -> Result<Value> {
    let text = fs::read_to_string("about.md").context("cannot read about.md")?;
    let (fields, body) = frontmatter::split(&text);
    let slugs: Vec<String> = categories.iter().map(|c| c.slug.clone()).collect();
    let mut about = Map::new();
    about.insert(
        "title".into(),
        json!(fields.get("title").unwrap_or("About Me")),
    );
    if let Some(intro) = fields.get("intro") {
        about.insert("intro".into(), json!(intro));
    }
    if let (Some(name), Some(url)) = (fields.get("company.name"), fields.get("company.url")) {
        about.insert("company".into(), json!({ "name": name, "url": url }));
    }
    let rendered = markdown::render(body, &slugs, CodeBlocks::Plain);
    about.insert("content".into(), json!(rendered.html));
    Ok(Value::Object(about))
}

fn write(path: &str, text: String) -> Result<()> {
    fs::write(path, text).with_context(|| format!("cannot write {path}"))
}

fn write_modules(categories: &[Category], articles: &[Article], about: &Value) -> Result<()> {
    let _ = fs::remove_dir_all(CONTENT_DIR);
    fs::create_dir_all(format!("{CONTENT_DIR}/articles"))?;
    let quote = |text: &str| serde_json::to_string(text).unwrap_or_default();

    write(
        &format!("{CONTENT_DIR}/site-data.js"),
        site_data(categories, articles, about)?,
    )?;

    // The parts of the application map: one static node per category and per article, so each
    // article is a page of its own, with its own analytics page and its own lazy chunk.
    let mut nodes = String::new();
    for category in categories {
        let description = if category.description.is_empty() {
            &category.name
        } else {
            &category.description
        };
        nodes.push_str(&format!(
            "  {}: {},\n",
            map_key(&category.slug)?,
            quote(description)
        ));
    }
    write(
        &format!("{CONTENT_DIR}/categories-map.js"),
        format!(
            "{GENERATED}import {{ appMap }} from 'imp'\n\nexport const category = appMap({{ description: 'The categories of the articles' }}, {{\n{nodes}}})\n"
        ),
    )?;

    let mut nodes = String::new();
    for article in articles {
        let description = if article.excerpt.is_empty() {
            &article.title
        } else {
            &article.excerpt
        };
        nodes.push_str(&format!("  {}: {},\n", article.key, quote(description)));
    }
    write(
        &format!("{CONTENT_DIR}/articles-map.js"),
        format!(
            "{GENERATED}import {{ appMap }} from 'imp'\n\nexport const articles = appMap({{ description: 'Every article' }}, {{\n{nodes}}})\n"
        ),
    )?;

    // The screens: a category page is part of the main bundle, each article is an area of its own
    let mut category_screens = String::new();
    for category in categories {
        category_screens.push_str(&format!(
            "  [app.category.{}]: () => categoryPage({}),\n",
            map_key(&category.slug)?,
            quote(&category.slug)
        ));
    }
    let mut article_screens = String::new();
    for article in articles {
        article_screens.push_str(&format!(
            "  [app.articles.{}]: area(() => import('./articles/{}.js')),\n",
            article.key, article.slug
        ));
    }
    write(
        &format!("{CONTENT_DIR}/routes.js"),
        format!(
            "{GENERATED}import {{ area }} from 'imp/router'
import {{ app }} from '../app-map.js'
import {{ categoryPage }} from '../pages/category-page.js'

export const categoryScreens = {{
{category_screens}}}

export const articleScreens = {{
{article_screens}}}
"
        ),
    )?;

    for article in articles {
        write(
            &format!("{CONTENT_DIR}/articles/{}.js", article.slug),
            format!(
                "{GENERATED}import {{ area }} from 'imp/router'
import {{ app }} from '../../app-map.js'
import {{ articlePage }} from '../../pages/article-page.js'

// The body of the article. Each <div data-code=\"N\"> is replaced by a codeBlock of code[N].
const content = {}

const code = {}

export default area({{
  screens: {{
    [app.articles.{}]: () => articlePage({}, content, code),
  }},
}})
",
                quote(&article.html),
                serde_json::to_string_pretty(&article.code)?,
                article.key,
                quote(&article.slug),
            ),
        )?;
    }
    Ok(())
}

fn copy_folder(from: &Path, to: &Path) -> Result<()> {
    fs::create_dir_all(to)?;
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_folder(&entry.path(), &target)?;
        } else {
            fs::copy(entry.path(), target)?;
        }
    }
    Ok(())
}

fn copy_images(categories: &[Category], articles: &[Article]) -> Result<()> {
    let _ = fs::remove_dir_all(HERO_DIR);
    fs::create_dir_all(HERO_DIR)?;
    for article in articles {
        if let Some((source, served)) = &article.image {
            fs::copy(source, format!("public{served}"))?;
        }
    }
    // Inline images of every category go to public/articles/images/
    let _ = fs::remove_dir_all("public/articles");
    fs::create_dir_all(INLINE_DIR)?;
    for category in categories {
        let images = Path::new("articles").join(&category.slug).join("images");
        if images.is_dir() {
            copy_folder(&images, Path::new(INLINE_DIR))?;
        }
    }
    Ok(())
}

/// Writes src/content/ from articles/ and about.md, and copies the images to public/
pub fn build_content() -> Result<Site> {
    let categories = read_categories()?;
    println!("Found {} categories", categories.len());
    let articles = read_articles(&categories)?;
    println!("Found {} articles", articles.len());
    let about = read_about(&categories)?;

    write_modules(&categories, &articles, &about)?;
    println!("Generated {CONTENT_DIR}/");
    copy_images(&categories, &articles)?;
    println!("Copied article images to public/");

    let about_title = about["title"].as_str().unwrap_or("About Me").to_string();
    Ok(Site {
        categories,
        articles,
        about_title,
    })
}

